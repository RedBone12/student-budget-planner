import { test, expect } from '@playwright/test';

test('preview CSV, import, combine filters, apply recurring expenses once and close a month', async ({ page }) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('charlie@example.com');
  await page.getByLabel('Password', { exact: true }).fill('Password1');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('link', { name: 'Planning', exact: true }).click();
  await page.getByLabel('Choose expense CSV').setInputFiles({ name: 'expenses.csv', mimeType: 'text/csv', buffer: Buffer.from('date,category,amount,notes\n2026-01-02,Groceries,12.50,CSV lunch\n2026-01-03,Groceries,30.00,CSV dinner') });
  await expect(page.getByRole('heading', { name: 'Import preview — 2 rows' })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm import', exact: true }).click();
  await expect(page.getByText('Imported 2 expenses; skipped 0 matching rows.')).toBeVisible();
  await page.getByRole('link', { name: 'Expenses', exact: true }).click();
  await page.getByLabel('Filter category').selectOption({ label: 'Groceries' });
  await page.getByLabel('From date', { exact: true }).fill('2026-01-01');
  await page.getByLabel('To date', { exact: true }).fill('2026-01-31');
  await page.getByLabel('Minimum amount (€)').fill('10');
  await page.getByLabel('Maximum amount (€)').fill('20');
  await expect(page.getByRole('cell', { name: 'CSV lunch', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'CSV dinner', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Planning', exact: true }).click();
  await page.getByLabel('Recurring category').selectOption({ label: 'Groceries' });
  await page.getByLabel('Recurring amount (€)').fill('5');
  const today = new Date().toISOString().slice(0, 10);
  await page.getByLabel('First due date').fill(today);
  await page.getByLabel('End date (optional)').fill(today);
  await page.getByRole('button', { name: 'Create recurring expense', exact: true }).click();
  await expect(page.getByText(/Recurring expense saved/)).toBeVisible();
  await page.getByRole('button', { name: 'Add due expenses now' }).click();
  await expect(page.getByText('Added 1 due expenses', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add due expenses now' }).click();
  await expect(page.getByText('Added 0 due expenses', { exact: true })).toBeVisible();
  await page.getByLabel('Settlement month').fill('2026-01');
  await page.getByRole('button', { name: 'Close month', exact: true }).click();
  await expect(page.getByText('Settlement saved for 2026-01')).toBeVisible();
  await page.reload();
  await page.locator('summary').filter({ hasText: '2026-01' }).click();
  await expect(page.getByText(/2 transactions/)).toBeVisible();
});
